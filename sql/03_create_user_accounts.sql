-- Drop existing user_account table only if explicitly re-running this migration
-- (Commented out by default to avoid unintended drops)
-- DROP TABLE USER_ACCOUNT CASCADE CONSTRAINTS;

CREATE TABLE USER_ACCOUNT (
    Account_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    Username VARCHAR2(50) NOT NULL UNIQUE,
    Password_Hash VARCHAR2(100) NOT NULL,
    Role VARCHAR2(20) NOT NULL CHECK (Role IN ('STUDENT', 'FACULTY', 'ADMINISTRATOR')),
    Student_ID NUMBER,
    Faculty_ID NUMBER,
    Is_Active NUMBER(1) DEFAULT 1 NOT NULL CHECK (Is_Active IN (0, 1)),
    Created_At TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    Last_Login TIMESTAMP,
    CONSTRAINT FK_ACC_STUDENT FOREIGN KEY (Student_ID) REFERENCES STUDENT(Student_ID) ON DELETE CASCADE,
    CONSTRAINT FK_ACC_FACULTY FOREIGN KEY (Faculty_ID) REFERENCES FACULTY(Faculty_ID) ON DELETE CASCADE,
    CONSTRAINT CK_ACCOUNT_REF CHECK (
        (Role = 'STUDENT' AND Student_ID IS NOT NULL AND Faculty_ID IS NULL) OR
        (Role = 'FACULTY' AND Faculty_ID IS NOT NULL AND Student_ID IS NULL) OR
        (Role = 'ADMINISTRATOR' AND Student_ID IS NULL AND Faculty_ID IS NULL)
    )
);

-- Index for high-performance username lookup during authentication
CREATE INDEX IDX_USER_ACCOUNT_USERNAME ON USER_ACCOUNT(Username);
CREATE INDEX IDX_USER_ACCOUNT_ROLE ON USER_ACCOUNT(Role);
