-- Smart Campus Management System — XYZ University
--
-- PURPOSE:
--   1. Ensures the additive USER_ACCOUNT table exists with BCrypt password hashing,
--      role enforcement, and relational foreign keys to STUDENT and FACULTY.
--   2. Provisions genuine credentials with the temporary development password '1234'
--      (BCrypt hashed: $2a$10$DzCZdFpiaTugCwgY5bK9LO..VM3enoPmmJnwNOJhstHOkePbmzL1i)
--      for all 60 Students, 15 Faculty Members, and the Administrator account.
--
-- SECURITY ADVISORY:
--   - Passwords are NEVER stored in plaintext.
--   - '1234' is a temporary development credential for demonstration and testing.
--   - In real-world deployment, individual secure credentials and first-login password
--     resets must be enforced.
--   - Idempotent: Can be run multiple times safely.
-- ==============================================================================

SET DEFINE OFF;
SET SERVEROUTPUT ON SIZE UNLIMITED;
SET LINESIZE 200;

