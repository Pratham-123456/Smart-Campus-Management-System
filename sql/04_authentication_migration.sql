-- 1. Ensure USER_ACCOUNT table exists
DECLARE
    v_table_exists NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_table_exists FROM user_tables WHERE table_name = 'USER_ACCOUNT';
    IF v_table_exists = 0 THEN
        EXECUTE IMMEDIATE '
        CREATE TABLE USER_ACCOUNT (
            Account_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
            Username VARCHAR2(50) NOT NULL UNIQUE,
            Password_Hash VARCHAR2(100) NOT NULL,
            Role VARCHAR2(20) NOT NULL CHECK (Role IN (''STUDENT'', ''FACULTY'', ''ADMINISTRATOR'')),
            Student_ID NUMBER,
            Faculty_ID NUMBER,
            Is_Active NUMBER(1) DEFAULT 1 NOT NULL CHECK (Is_Active IN (0, 1)),
            Created_At TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            Last_Login TIMESTAMP,
            CONSTRAINT FK_ACC_STUDENT FOREIGN KEY (Student_ID) REFERENCES STUDENT(Student_ID) ON DELETE CASCADE,
            CONSTRAINT FK_ACC_FACULTY FOREIGN KEY (Faculty_ID) REFERENCES FACULTY(Faculty_ID) ON DELETE CASCADE,
            CONSTRAINT CK_ACCOUNT_REF CHECK (
                (Role = ''STUDENT'' AND Student_ID IS NOT NULL AND Faculty_ID IS NULL) OR
                (Role = ''FACULTY'' AND Faculty_ID IS NOT NULL AND Student_ID IS NULL) OR
                (Role = ''ADMINISTRATOR'' AND Student_ID IS NULL AND Faculty_ID IS NULL)
            )
        )';
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_USER_ACCOUNT_USERNAME ON USER_ACCOUNT(Username)';
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_USER_ACCOUNT_ROLE ON USER_ACCOUNT(Role)';
        DBMS_OUTPUT.PUT_LINE('Table USER_ACCOUNT created successfully.');
    ELSE
        DBMS_OUTPUT.PUT_LINE('Table USER_ACCOUNT already exists.');
    END IF;
END;
/

-- 2. Controlled Development Provisioning for All Roles
DECLARE
    v_hash VARCHAR2(100) := '$2a$10$DzCZdFpiaTugCwgY5bK9LO..VM3enoPmmJnwNOJhstHOkePbmzL1i'; -- BCrypt('1234')
    v_student_created NUMBER := 0;
    v_student_reset NUMBER := 0;
    v_faculty_created NUMBER := 0;
    v_faculty_reset NUMBER := 0;
    v_admin_created NUMBER := 0;
    v_existing_id NUMBER;
BEGIN
    DBMS_OUTPUT.PUT_LINE('-----------------------------------------------------------------');
    DBMS_OUTPUT.PUT_LINE('PROVISIONING ACCOUNTS FOR ALL STUDENTS, FACULTY & ADMINISTRATOR...');
    DBMS_OUTPUT.PUT_LINE('-----------------------------------------------------------------');

    -- A. Administrator Account ('admin' / '1234')
    v_existing_id := NULL;
    BEGIN
        SELECT Account_ID INTO v_existing_id FROM USER_ACCOUNT WHERE Role = 'ADMINISTRATOR' AND Username = 'admin';
    EXCEPTION WHEN NO_DATA_FOUND THEN v_existing_id := NULL;
    END;

    IF v_existing_id IS NULL THEN
        INSERT INTO USER_ACCOUNT (Username, Password_Hash, Role, Is_Active, Created_At)
        VALUES ('admin', v_hash, 'ADMINISTRATOR', 1, CURRENT_TIMESTAMP);
        v_admin_created := v_admin_created + 1;
        DBMS_OUTPUT.PUT_LINE('[PROVISIONED] Administrator account: admin (Role: ADMINISTRATOR)');
    ELSE
        UPDATE USER_ACCOUNT SET Password_Hash = v_hash WHERE Account_ID = v_existing_id;
        DBMS_OUTPUT.PUT_LINE('[UPDATED]     Administrator account: admin (Password set to 1234)');
    END IF;

    -- B. Student Accounts (Student_ID / '1234')
    FOR s IN (SELECT Student_ID, Name FROM STUDENT ORDER BY Student_ID ASC) LOOP
        v_existing_id := NULL;
        BEGIN
            SELECT Account_ID INTO v_existing_id FROM USER_ACCOUNT WHERE Student_ID = s.Student_ID;
        EXCEPTION WHEN NO_DATA_FOUND THEN v_existing_id := NULL;
        END;

        IF v_existing_id IS NULL THEN
            INSERT INTO USER_ACCOUNT (Username, Password_Hash, Role, Student_ID, Is_Active, Created_At)
            VALUES (TO_CHAR(s.Student_ID), v_hash, 'STUDENT', s.Student_ID, 1, CURRENT_TIMESTAMP);
            v_student_created := v_student_created + 1;
        ELSE
            UPDATE USER_ACCOUNT SET Password_Hash = v_hash, Username = TO_CHAR(s.Student_ID), Role = 'STUDENT'
            WHERE Account_ID = v_existing_id;
            v_student_reset := v_student_reset + 1;
        END IF;
    END LOOP;

    -- C. Faculty Accounts (Faculty_ID / '1234')
    FOR f IN (SELECT Faculty_ID, Name FROM FACULTY ORDER BY Faculty_ID ASC) LOOP
        v_existing_id := NULL;
        BEGIN
            SELECT Account_ID INTO v_existing_id FROM USER_ACCOUNT WHERE Faculty_ID = f.Faculty_ID;
        EXCEPTION WHEN NO_DATA_FOUND THEN v_existing_id := NULL;
        END;

        IF v_existing_id IS NULL THEN
            INSERT INTO USER_ACCOUNT (Username, Password_Hash, Role, Faculty_ID, Is_Active, Created_At)
            VALUES (TO_CHAR(f.Faculty_ID), v_hash, 'FACULTY', f.Faculty_ID, 1, CURRENT_TIMESTAMP);
            v_faculty_created := v_faculty_created + 1;
        ELSE
            UPDATE USER_ACCOUNT SET Password_Hash = v_hash, Username = TO_CHAR(f.Faculty_ID), Role = 'FACULTY'
            WHERE Account_ID = v_existing_id;
            v_faculty_reset := v_faculty_reset + 1;
        END IF;
    END LOOP;

    COMMIT;
    DBMS_OUTPUT.PUT_LINE('-----------------------------------------------------------------');
    DBMS_OUTPUT.PUT_LINE('PROVISIONING AUDIT SUMMARY:');
    DBMS_OUTPUT.PUT_LINE('  Students : ' || v_student_created || ' created, ' || v_student_reset || ' updated (Total: ' || (v_student_created + v_student_reset) || ')');
    DBMS_OUTPUT.PUT_LINE('  Faculty  : ' || v_faculty_created || ' created, ' || v_faculty_reset || ' updated (Total: ' || (v_faculty_created + v_faculty_reset) || ')');
    DBMS_OUTPUT.PUT_LINE('  Admin    : admin provisioned/updated');
    DBMS_OUTPUT.PUT_LINE('-----------------------------------------------------------------');
END;
/

